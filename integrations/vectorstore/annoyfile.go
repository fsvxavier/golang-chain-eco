package vectorstore

import (
	"context"
	"encoding/binary"
	"errors"
	"fmt"
	"math"
	"os"
	"sort"
	"strconv"
)

// ErrReadOnlyIndex is returned by Upsert and Delete on an index read from a
// foreign file (AnnoyFile, FAISSFlat).
var ErrReadOnlyIndex = errors.New("vectorstore: index loaded from a file is read-only")

// AnnoyFile reads a native Annoy index (.ann, written by annoy's save()).
//
// Layout (annoylib.h, little-endian, no file header): a flat array of fixed
// size nodes, all 4-byte fields.
//
//	angular:   n_descendants int32 | children[2] int32 | v[dim] float32
//	euclidean: n_descendants int32 | a float32 | children[2] int32 | v[dim] float32
//
// Items are nodes 0..n-1 with n_descendants == 1; the item id is the node
// index. The tree nodes and the root copies follow; the last node's
// n_descendants is the item count.
//
// ponytail: Query is brute force over the item vectors, not a walk of the
// trees, so it is exact and the forest is ignored. Walking the trees (the
// children/hyperplane fields) is the upgrade when a file is too big to scan.
//
// Compatibility with files produced by the real annoy library is NOT verified
// by the tests here: they write files with the same layout in Go. See
// docs/INTEGRATIONS.md for how to check with a file generated by Python.
type AnnoyFile struct {
	Dim    int
	Metric string         // "angular" or "euclidean"
	DocIDs map[int]string // optional item id -> document id; nil means the decimal item id
	vecs   [][]float32
}

var _ Backend = (*AnnoyFile)(nil)

// LoadAnnoyFile reads an Annoy index of dimension dim built with metric
// "angular" or "euclidean". The dimension and metric are not stored in the
// file, so the caller must supply them.
func LoadAnnoyFile(path string, dim int, metric string) (*AnnoyFile, error) {
	if dim <= 0 {
		return nil, fmt.Errorf("annoy: dimension must be positive, got %d", dim)
	}
	var voff int // byte offset of v inside a node
	switch metric {
	case "angular":
		voff = 12
	case "euclidean":
		voff = 16
	default:
		return nil, fmt.Errorf("annoy: unsupported metric %q (want angular or euclidean)", metric)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	node := voff + 4*dim
	if len(data) == 0 || len(data)%node != 0 {
		return nil, fmt.Errorf("annoy: file size %d is not a multiple of the node size %d (dim %d, %s)", len(data), node, dim, metric)
	}
	nodes := len(data) / node
	nDesc := func(i int) int32 { return int32(binary.LittleEndian.Uint32(data[i*node:])) }
	items := int(nDesc(nodes - 1))
	if items <= 0 || items > nodes {
		return nil, fmt.Errorf("annoy: bad item count %d in a file of %d nodes", items, nodes)
	}
	f := &AnnoyFile{Dim: dim, Metric: metric, vecs: make([][]float32, items)}
	for i := range items {
		if nDesc(i) != 1 {
			return nil, fmt.Errorf("annoy: node %d is not an item (n_descendants=%d)", i, nDesc(i))
		}
		v := make([]float32, dim)
		for j := range v {
			off := i*node + voff + 4*j
			v[j] = math.Float32frombits(binary.LittleEndian.Uint32(data[off:]))
		}
		f.vecs[i] = v
	}
	return f, nil
}

// Len is the number of items in the file.
func (f *AnnoyFile) Len() int { return len(f.vecs) }

func (f *AnnoyFile) docID(i int) string {
	if s, ok := f.DocIDs[i]; ok {
		return s
	}
	return strconv.Itoa(i)
}

// Query returns the k best items. Score is the cosine for "angular" and the
// negated Euclidean distance for "euclidean" (higher is better).
func (f *AnnoyFile) Query(_ context.Context, q []float32, k int) ([]Hit, error) {
	hits := make([]Hit, len(f.vecs))
	for i, v := range f.vecs {
		s := cosine(q, v)
		if f.Metric == "euclidean" {
			s = -dist(q, v)
		}
		hits[i] = Hit{Record{ID: f.docID(i), Vector: v}, s}
	}
	return rankHits(hits, k), nil
}

func (f *AnnoyFile) Upsert(context.Context, []Record) error { return ErrReadOnlyIndex }
func (f *AnnoyFile) Delete(context.Context, []string) error { return ErrReadOnlyIndex }

func dist(a, b []float32) float64 {
	var s float64
	for i := 0; i < len(a) && i < len(b); i++ {
		d := float64(a[i]) - float64(b[i])
		s += d * d
	}
	return math.Sqrt(s)
}

// rankHits sorts by score (desc), then ID, and keeps the first k.
func rankHits(hits []Hit, k int) []Hit {
	sort.SliceStable(hits, func(i, j int) bool {
		if hits[i].Score != hits[j].Score {
			return hits[i].Score > hits[j].Score
		}
		return hits[i].ID < hits[j].ID
	})
	if len(hits) > k {
		hits = hits[:k]
	}
	return hits
}
